static int extractBitFromName(const std::string& cellType) {
    std::vector<size_t> underscores;
    for (size_t i = 0; i < cellType.size(); i++) {
        if (cellType[i] == '_') underscores.push_back(i);
    }

    if (underscores.size() >= 2) {
        // 第二? '_' 前面的 token
        std::string token = cellType.substr(underscores[1 - 1] + 1, underscores[1] - underscores[1 - 1] - 1);
        // ↑ (第一? '_' 之後，第二? '_' 之前)

        // 找 token 裡的數字
        std::regex numRx(R"((\d+))");
        std::smatch m;
        if (std::regex_search(token, m, numRx)) {
            int width = std::stoi(m[1]);
            std::cout << "DEBUG: getBitWidth(\"" << cellType << "\") -> " << width
                << " (from token: " << token << ")\n";
            return width;
        }
    }

    // 沒找到數字，預設 1
    std::cout << "DEBUG: getBitWidth(\"" << cellType << "\") -> 1 (default)\n";
    return 1;
}

std::string pickMbffTarget(const std::vector<std::string>& candidates, int bit) {
    // 先挑 bit 符合者；若有多?，預設挑名字最短/字典序最小（?定）
    std::vector<std::string> filt;
    for (const auto& c : candidates) if (extractBitFromName(c) == bit) filt.push_back(c);
    if (filt.empty()) return "";
    std::sort(filt.begin(), filt.end(),
        [](const std::string& a, const std::string& b) {
            if (a.size() != b.size()) return a.size() < b.size();
            return a < b;
        });
    return filt.front();
}
